    // ── fixture + pin laws ───────────────────────────────────────────────

    private static function fixture_path(): string
    {
        return dirname(__DIR__, 2) . '/Fixtures/Contracts/error-codes.json';
    }

    private static function pin_path(): string
    {
        return dirname(__DIR__, 2) . '/Fixtures/Contracts/error-codes.pin.txt';
    }

    public static function src_root(): string
    {
        return dirname(__DIR__, 3) . '/src';
    }

    /** @return list<string> */
    public static function registry_codes(): array
    {
        $decoded = self::read_json(self::fixture_path());
        if (!is_array($decoded) || !isset($decoded['codes']) || !is_array($decoded['codes'])) {
            self::fail('the vendored registry must decode to {codes: [...]}.');
        }
        /** @var list<string> $codes */
        $codes = $decoded['codes'];
        return $codes;
    }

    /** @return array<mixed>|list<mixed>|null */
    private static function read_json(string $path): mixed
    {
        return json_decode(self::read_text($path), true, 512, JSON_THROW_ON_ERROR);
    }

    private static function read_text(string $path): string
    {
        self::assertFileExists($path);
        $raw = file_get_contents($path);
        self::assertIsString($raw);
        return $raw;
    }

    public function test_the_fixture_is_vendored_from_the_pinned_contract_tag(): void
    {
        $pin = trim(self::read_text(self::pin_path()));

        $this->assertSame(
            self::CONTRACTS_TAG,
            $pin,
            "the sidecar pin says '{$pin}' but this test hardcodes '" . self::CONTRACTS_TAG . "'. "
            . 'Re-vendor tests/Fixtures/Contracts/error-codes.json from the @phlix/contracts tag this test names, and keep both files in lockstep.',
        );
    }

    public function test_the_fixture_is_generator_output_not_a_hand_written_impostor(): void
    {
        $raw = self::read_text(self::fixture_path());

        $this->assertStringContainsString(
            self::GENERATOR_MARKER,
            $raw,
            'error-codes.json must stay the byte-copy of dist/error-codes.json produced by the contracts generator.',
        );
    }

    public function test_the_registry_clears_the_anti_vacuity_floor(): void
    {
        $codes = self::registry_codes();

        $this->assertGreaterThanOrEqual(
            self::MIN_REGISTRY_CODES,
            count($codes),
            'a truncated re-vendor cannot pass: the floor records the size of the registry at adoption time.',
        );
        $this->assertSame(array_values(array_unique($codes)), $codes, 'registry codes must be unique and in declared order.');
    }

    // ── the emit law ──────────────────────────────────────────────────────

    public function test_every_code_channel_literal_is_registered(): void
    {
        $registry = array_flip(self::registry_codes());
        $sites = ErrorCodeScan::run(self::src_root());

        $distinct = [];
        $violations = [];
        foreach ($sites as $site) {
            if ($site['kind'] !== 'literal' && $site['kind'] !== 'const') {
                continue;
            }
            if (isset(self::exception_keys()[self::site_key($site)])) {
                continue;
            }
            $distinct[$site['value']] = true;
            if (!isset($registry[$site['value']])) {
                $violations[] = "{$site['file']}:{$site['line']} [{$site['channel']}] '{$site['value']}' (expr: {$site['snippet']})";
            }
        }

        $this->assertGreaterThanOrEqual(
            self::MIN_SCANNED_DISTINCT_CODES,
            count($distinct),
            'the scanner found almost no code-channel literals — the positional patterns broke; fix the scan, do not celebrate a green law.',
        );

        $this->assertSame(
            [],
            $violations,
            "codes placed on a wire code field but absent from the vendored registry (fix the CONTRACT first, then re-vendor; never invent):\n"
            . implode("\n", $violations),
        );
    }

    public function test_emitted_codes_cover_both_channels(): void
    {
        $channels = [];
        foreach (ErrorCodeScan::run(self::src_root()) as $site) {
            $channels[$site['channel']] = ($channels[$site['channel']] ?? 0) + 1;
        }

        $this->assertArrayHasKey('rest', $channels, 'the REST channel scanner stopped matching anything — positional patterns broke.');
        $this->assertArrayHasKey('ws', $channels, 'the WS channel scanner stopped matching anything — positional patterns broke.');
    }

    public function test_every_non_literal_code_channel_site_is_whitelisted_and_live(): void
    {
        $scan = [];
        foreach (ErrorCodeScan::run(self::src_root()) as $site) {
            if ($site['kind'] === 'nonliteral' || $site['kind'] === 'const-unresolved') {
                $scan[self::site_key($site)] = $site;
            }
        }

        $whitelist = [];
        foreach (self::NON_LITERAL_WHITELIST as $entry) {
            $key = "{$entry['file']}|{$entry['channel']}|{$entry['expr']}";
            $this->assertArrayNotHasKey($key, $whitelist, "duplicate whitelist entry: {$key}");
            $this->assertNotSame('', $entry['reason'], "every whitelist entry needs a reason: {$key}");
            $whitelist[$key] = $entry;
        }

        $unwhitelisted = array_values(array_diff(array_keys($scan), array_keys($whitelist)));
        $stale = array_values(array_diff(array_keys($whitelist), array_keys($scan)));

        $this->assertSame(
            [],
            $unwhitelisted,
            "non-literal code-channel sites without a whitelisted reason (classify them, or route their values through the registry-checked Response::error()/jsonError() pattern):\n"
            . implode("\n", $unwhitelisted),
        );
        $this->assertSame(
            [],
            $stale,
            "whitelist entries whose site no longer exists in src/ — the tree moved, prune the list:\n"
            . implode("\n", $stale),
        );
    }

    public function test_every_literal_exception_is_registered_anchored_and_live(): void
    {
        $scan = [];
        foreach (ErrorCodeScan::run(self::src_root()) as $site) {
            if ($site['kind'] === 'literal') {
                $scan[self::site_key($site)] = $site;
            }
        }

        $seen = [];
        foreach (self::LITERAL_EXCEPTIONS as $entry) {
            $key = "{$entry['file']}|{$entry['channel']}|{$entry['expr']}";
            $this->assertArrayNotHasKey($key, $seen, "duplicate literal exception: {$key}");
            $this->assertNotSame('', $entry['reason'], "every literal exception needs a reason: {$key}");
            $this->assertArrayHasKey(
                $key,
                $scan,
                "literal exception '{$key}' matches no scanned site — prune it (the tree moved or the pattern broke).",
            );
            $seen[$key] = true;
        }
    }

    // ── emitter + dynamic-code laws ───────────────────────────────────────

    public function test_emitter_table_matches_live_signatures(): void
    {
        foreach (self::CODE_EMITTERS as $emitter) {
            $method = new ReflectionMethod("{$emitter['class']}::{$emitter['method']}");
            $params = $method->getParameters();
            $this->assertArrayHasKey(
                $emitter['arg'],
                $params,
                "{$emitter['class']}::{$emitter['method']}() has no argument {$emitter['arg']} — the emitter table lies.",
            );
            $param = $params[$emitter['arg']];
            $this->assertSame(
                $emitter['param'],
                $param->getName(),
                "the emitter table expects parameter \${$emitter['param']} at position {$emitter['arg']} of {$emitter['method']}().",
            );
            $type = $param->getType();
            $this->assertInstanceOf(ReflectionNamedType::class, $type);
            $this->assertSame('string', $type->getName());
        }
    }

    public function test_every_string_code_parameter_is_a_declared_emitter(): void
    {
        $declared = [];
        foreach (self::CODE_EMITTERS as $emitter) {
            $declared["{$emitter['class']}::{$emitter['method']}"] = true;
        }

        $undeclared = [];
        foreach (ErrorCodeScan::emitterDefinitions(self::src_root()) as $fqn) {
            if (!isset($declared[$fqn])) {
                $undeclared[] = $fqn;
            }
        }

        $this->assertSame(
            [],
            $undeclared,
            "methods declaring an int-first `string \$code` signature returning Response/self are code emitters — register them in CODE_EMITTERS (or rename the parameter):\n"
            . implode("\n", $undeclared),
        );
    }

    public function test_dynamic_code_channel_codes_are_registered(): void
    {
        $registry = array_flip(self::registry_codes());
        foreach (self::DYNAMIC_CODE_CHANNELS as $code) {
            $this->assertArrayHasKey($code, $registry, "a code reachable via a dynamic code channel is not in the registry: {$code}");
        }

        foreach (self::DYNAMIC_CODE_CHANNEL_ANCHORS as $relFile => $anchors) {
            $raw = self::read_text(self::src_root() . '/' . $relFile);
            foreach ($anchors as $anchor) {
                $this->assertStringContainsString(
                    $anchor,
                    $raw,
                    "the dynamic-code-channel anchor '{$anchor}' vanished from {$relFile} — re-audit the channel.",
                );
            }
        }
    }

    /**
     * The REST-emittable set: every code the server can place on `Error.code`.
     * Consumed by {@see ErrorCodesOpenApiEnumContractTest}.
     *
     * @return list<string> registry-declared order
     */
    public static function rest_emittable_codes(): array
    {
        $found = [];
        foreach (ErrorCodeScan::run(self::src_root()) as $site) {
            if (($site['kind'] === 'literal' || $site['kind'] === 'const') && $site['channel'] === 'rest') {
                if (isset(self::exception_keys()[self::site_key($site)])) {
                    continue;
                }
                $found[$site['value']] = true;
            }
        }
        foreach (self::DYNAMIC_CODE_CHANNELS as $code) {
            $found[$code] = true;
        }

        $registry = self::registry_codes();
        $ordered = [];
        foreach ($registry as $code) {
            if (isset($found[$code])) {
                $ordered[] = $code;
            }
        }
        // Anything the scan found that the registry does not declare cannot be
        // ordered — the emit law already reddens on it first; surface it loudly
        // here too rather than silently dropping it from the enum.
        foreach (array_keys($found) as $code) {
            if (!in_array((string) $code, $registry, true)) {
                $ordered[] = (string) $code;
            }
        }
        return $ordered;
    }

    /** @return array<string, true> */
    private static function exception_keys(): array
    {
        $out = [];
        foreach (self::LITERAL_EXCEPTIONS as $entry) {
            $out["{$entry['file']}|{$entry['channel']}|{$entry['expr']}"] = true;
        }
        return $out;
    }

    /**
     * @param array{file: string, line: int, channel: string, kind: string, value?: string, snippet: string} $site
     */
    private static function site_key(array $site): string
    {
        return "{$site['file']}|{$site['channel']}|{$site['snippet']}";
    }
}

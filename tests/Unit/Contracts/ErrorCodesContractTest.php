    /**
     * Literals at code-channel positions that are not wire emits (logged
     * sentinels). Live-anchored like NON_LITERAL_WHITELIST.
     *
     * @var list<array{file: string, expr: string, channel: string, reason: string}>
     */
    public const LITERAL_EXCEPTIONS = [
        ['file' => 'Hub/HubClient.php', 'expr' => '$response->getErrorCode() ?? \'UNKNOWN\'', 'channel' => 'ws', 'reason' => 'hub-log sentinel, not a wire emit'],
    ];

    /**
     * Codes that reach the REST `code` field through a dynamic expression the
     * scanner cannot resolve (an exception property fed by named constructors).
     * Declared here, registry-checked here; the enum law inherits them.
     *
     * @var list<string>
     */
    public const DYNAMIC_CODE_CHANNELS = [
        'auth.account_pending',          // AccountInactiveException::ERROR_PENDING  via forStatus()
        'auth.account_disabled',         // AccountInactiveException::ERROR_DISABLED via forStatus()
        'auth.password_change_required', // PasswordChangeRequiredException::ERROR_CODE
    ];

    /**
     * file => snippets whose presence keeps DYNAMIC_CODE_CHANNELS honest.
     *
     * @var array<string, list<string>>
     */
    public const DYNAMIC_CODE_CHANNEL_ANCHORS = [
        'Auth/AccountInactiveException.php' => ['self::ERROR_PENDING', 'self::ERROR_DISABLED'],
        'Auth/PasswordChangeRequiredException.php' => ['self::ERROR_CODE'],
        'Server/Http/Controllers/AuthController.php' => ['$e->errorCode'],

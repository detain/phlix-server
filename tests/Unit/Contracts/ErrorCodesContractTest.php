/**
 * W2 (error-code doctrine) — the server consumes the @phlix/contracts error-code
 * registry, and every code the server places on a wire `code`/`error_code` field
 * is a registered member.
 *
 * ## What this file enforces
 *
 *  1. **Vendored-fixture honesty.** `tests/Fixtures/Contracts/error-codes.json` is
 *     a byte-copy of `dist/error-codes.json` from the @phlix/contracts tag
 *     {@see ErrorCodesContractTest::CONTRACTS_TAG}. The fixture's own `$comment`
 *     must still carry the generator marker (a hand-written impostor fails), the
 *     sidecar pin file must name the same tag this test hardcodes (re-vendor is a
 *     two-file lockstep edit), and the registry must clear the anti-vacuity floor.
 *
 *  2. **The emit law.** A positional scan ({@see ErrorCodeScan}) of every PHP
 *     file under `src/` finds each expression the source places on a code-carrying
 *     wire field, and every literal found there must be a member of the vendored
 *     registry. The scan is POSITIONAL, not shape-based: a dotted string appearing
 *     anywhere (config key, webhook event name, codec profile) is NOT an emitted
 *     code. A whole-tree shape census was measured before this law was written and
 *     surfaced 174 non-registry dotted literals that are not error codes at all —
 *     positional scanning is why this law does not need a hand-written denylist.
 *
 *  3. **Channels.** A scanned site is `ws` when its value travels on a SyncPlay
 *     WebSocket frame (`Messages::error()` arg 0, `sendError()` arg 1, an
 *     `'error_code' =>` array key) and `rest` otherwise (`'code' =>` array key,
 *     `Response::error()` arg 1, `jsonError()` arg 1). The split exists because
 *     {@see ErrorCodesOpenApiEnumContractTest} pins only the REST channel against
 *     `openapi.yaml` `Error.code` — the WS channel carries the legacy SCREAMING
 *     and dotted-twin vocabularies and is specified by the SyncPlay wire SPEC,
 *     not by this OpenAPI document.
 *
 *  4. **Emitter allow-list pin.** The call-argument patterns are driven by an
 *     explicit emitter table ({@see CODE_EMITTERS}); every entry's signature is
 *     re-checked against reflection on every run, so renaming the `$code`
 *     parameter, deleting a helper, or pointing the table at a non-string
 *     parameter reddens this test instead of silently shrinking coverage. The
 *     definition-side twin ({@see test_every_string_code_parameter_is_a_declared_emitter()})
 *     reddens when a NEW helper declares an int-first `string $code` signature
 *     returning Response/self and nobody registers it — the hole is closed from
 *     both sides.
 *
 *  5. **Whitelist honesty.** Non-literal code-channel expressions (variables,
 *     properties, calls) cannot be registry-checked statically. Each such site is
 *     listed in {@see NON_LITERAL_WHITELIST} with file, normalized expression,
 *     channel and reason — and the list is LIVE-checked in both directions: every
 *     scanned non-literal site must appear in it, and every entry must match a
 *     site still present in the tree, so the list cannot fossilize.
 *     {@see LITERAL_EXCEPTIONS} works the same way for logged sentinels that
 *     merely look like code emissions.
 *
 * Fix the CONTRACT first (phlix-contracts src/errors.ts, retag, re-vendor), then
 * the emitter. Never invent a code in server source.
 *
 * @package Phlix
 */
final class ErrorCodesContractTest extends TestCase
{
    /**
     * The contracts tag the fixture was vendored from. Bumping this WITHOUT
     * re-vendoring reddens {@see test_the_fixture_is_vendored_from_the_pinned_contract_tag()};
     * re-vendoring a different tag WITHOUT bumping this reddens it too.
     */
    public const CONTRACTS_TAG = 'v0.5.1';

    public const GENERATOR_MARKER = 'GENERATED by scripts/emit-error-codes.mjs';

    /**
     * Anti-vacuity floor: the v0.5.1 registry carries 202 codes; 147 is the floor
     * recorded when this lane opened. A truncated re-vendor cannot pass.
     */

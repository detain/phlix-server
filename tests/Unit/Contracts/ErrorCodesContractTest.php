        ['class' => Response::class, 'method' => 'error', 'arg' => 1, 'channel' => 'rest', 'param' => 'code'],
        ['class' => PluginAdminController::class, 'method' => 'jsonError', 'arg' => 1, 'channel' => 'rest', 'param' => 'code'],
        ['class' => PluginCatalogController::class, 'method' => 'jsonError', 'arg' => 1, 'channel' => 'rest', 'param' => 'code'],
    ];


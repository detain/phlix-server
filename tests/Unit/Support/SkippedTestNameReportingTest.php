        $result = $this->runScript($this->fixtureFile('colors.log', $output));

        self::assertSame(
            0,
            $result['exit'],
            'a colorized run parses correctly apart from the escapes, so refusing it as "not a '
            . "PHPUnit run\" would be a false diagnosis. stderr:\n" . $result['stderr'],
        );
        self::assertSame([self::REAL_SKIPPED_NAME], $result['lines'], $result['stderr']);
    }

    public function test_a_truncated_write_is_refused_instead_of_handing_comm_a_short_set(): void
    {
        // `sort`'s exit status must be checked: a failing write (ENOSPC here, SIGPIPE in a
        // pipeline) otherwise yields a TRUNCATED set and exit 0 — the precise "quietly wrong
        // set handed to comm" outcome the whole exit contract exists to prevent.
        $output = $this->runRealPhpunit([self::REAL_TEST_FILE]);
        $input = $this->fixtureFile('write-fail.log', $output);

        if (!is_writable('/dev/full')) {
            // No always-full device on this box, so the failure cannot be provoked; pin the
            // mechanism textually rather than reporting a pass that measured nothing.
            self::assertStringContainsString(
                'write_status',
                (string) file_get_contents(self::SCRIPT),
                '/dev/full is unavailable, so the truncated-write path cannot be exercised here; '
                . "the script must still check the status of its `sort` pipeline",
            );

            return;
        }

        $stderrFile = $this->tmpDir . '/full-stderr.txt';
        $exit = 0;
        exec(
            escapeshellarg(self::SCRIPT) . ' ' . escapeshellarg($input)
            . ' > /dev/full 2> ' . escapeshellarg($stderrFile),
            $ignored,
            $exit,
        );

        self::assertSame(6, $exit, (string) file_get_contents($stderrFile));
        self::assertStringContainsString(
            'stdout is TRUNCATED',
            (string) file_get_contents($stderrFile),
        );
    }


    public function test_it_emits_the_sorted_name_set_and_nothing_else(): void
    {
        $result = $this->runScript($this->fixtureFile('run.log'));

        self::assertSame(0, $result['exit'], $result['stderr']);
        self::assertSame(self::EXPECTED_NAMES, $result['lines'], $result['stderr']);

        // "nothing else", asserted on the RAW bytes rather than on a filtered array: a blank
        // line is a set member as far as `comm` is concerned, and leading whitespace changes
        // the byte comparison.
        self::assertSame(
            implode("\n", self::EXPECTED_NAMES) . "\n",
            $result['stdout'],
            'stdout must be exactly the set, newline-terminated, with no blank or indented lines',
        );

        // Sortedness is delivered by the assertion ABOVE, because the fixture lists the names
        // in a different order from the sorted one. Pin that premise instead of re-sorting an
        // already-sorted array, which cannot fail.
        $asPrinted = [];
        preg_match_all('/^[0-9]+\) (\S+::\S.*)$/m', self::FIXTURE, $matches);
        foreach ($matches[1] as $name) {
            $asPrinted[] = trim($name);
        }

        self::assertNotSame(
            self::EXPECTED_NAMES,
            array_slice($asPrinted, 1),
            'the fixture must print the names in an UNSORTED order, or the assertion above cannot '
            . 'prove that the script sorts',
        );
    }


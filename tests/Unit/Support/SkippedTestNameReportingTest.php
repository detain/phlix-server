    /**
     * The branch findings 1 and 2 both fired and which nothing reached: the summaries
     * report MORE skips than the detail lists declared, without testdox output to explain
     * it and with a non-empty list (so neither exit 5 nor exit 4 applies). The shape is
     * real — a whole-workflow log in which one job did not load `phpunit.xml`.
     */
    public function test_a_list_that_names_fewer_skips_than_the_summary_is_refused_as_partial(): void
    {
        $partial = "PHPUnit 10.5.64\n\nThere was 1 skipped test:\n\n"
            . "1) Phlix\Tests\Unit\Alpha\AlphaTest::testGamma\nreason\n\n"
            . "OK, but some tests were skipped!\nTests: 9, Assertions: 12, Skipped: 3.\n";

        $result = $this->runScript($this->fixtureFile('partial.log', $partial));

        self::assertSame(3, $result['exit'], 'a set missing 2 of 3 names must not be handed to `comm`');
        self::assertSame([], $result['lines'], 'a PARTIAL set must not be written');
        self::assertStringContainsString('2 name(s) are missing', $result['stderr']);
    }

    /**
     * The mirror image, and the reason the `No tests executed!` allowance is conditional:
     * MORE declared than summarised, with no run reporting `No tests executed!`, can only
     * be the parser over-counting.
     */
    public function test_a_list_that_names_more_skips_than_the_summary_is_refused_as_drift(): void
    {
        $over = "PHPUnit 10.5.64\n\nThere were 2 skipped tests:\n\n"
            . "1) Phlix\Tests\Unit\Alpha\AlphaTest::testGamma\nreason\n\n"
            . "2) Phlix\Tests\Unit\Beta\BetaTest::testDelta\nreason\n\n"
            . "OK, but some tests were skipped!\nTests: 9, Assertions: 12, Skipped: 1.\n";

        $result = $this->runScript($this->fixtureFile('over.log', $over));

        self::assertSame(3, $result['exit'], 'over-counting is drift and must be loud');
        self::assertSame([], $result['lines']);
        self::assertStringContainsString('No tests executed!', $result['stderr']);
    }


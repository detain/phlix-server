        self::assertTrue(mkdir($dir, 0o700), 'could not create the fixture directory');
        $this->tmpDir = $dir;
    }

    protected function tearDown(): void
    {
        if ($this->tmpDir === '') {
            return;
        }

        foreach ((glob($this->tmpDir . '/*') ?: []) as $file) {
            @unlink($file);
        }

        @rmdir($this->tmpDir);
        $this->tmpDir = '';
    }


    public function test_the_set_is_ordered_BYTE_wise_so_comm_accepts_it(): void
    {
        $run = "PHPUnit 10.5.64\n\nThere were 2 skipped tests:\n\n"
            . '1) ' . self::C_ORDER_PAIR[1] . "\nreason\n\n"
            . '2) ' . self::C_ORDER_PAIR[0] . "\nreason\n\n"
            . "OK, but some tests were skipped!\nTests: 4, Assertions: 4, Skipped: 2.\n";

        $file = $this->fixtureFile('locale.log', $run);
        $utf8Locale = $this->localeWhoseCollationDiffersFromC();

        // Run the script under a locale whose collation would reorder these two names, so that
        // dropping the script's own `LC_ALL=C` changes the output. `comm` compares byte-wise
        // (GNU coreutils 9.4: it rejects a locale-ordered file with "is not in sorted order").
        $result = $this->runScript($file, $utf8Locale === null ? [] : ['LC_ALL' => $utf8Locale]);

        self::assertSame(0, $result['exit'], $result['stderr']);
        self::assertSame(
            self::C_ORDER_PAIR,
            $result['lines'],
            'the set must be in BYTE order (LC_ALL=C), whatever locale the caller runs under, '
            . 'or GNU `comm` refuses it as unsorted. Ambient locale for this run: '
            . ($utf8Locale ?? 'none available that collates differently from C'),
        );

        if ($utf8Locale === null) {
            // No locale on this box reorders the pair, so the behavioural check above cannot
            // fail. Fall back to pinning the mechanism textually rather than reporting a pass
            // that proves nothing.
            self::assertStringContainsString(
                'LC_ALL=C sort -u',
                (string) file_get_contents(self::SCRIPT),
                'no locale on this box collates differently from C, so the byte-order property '
                . 'cannot be measured here; the script must still pin LC_ALL=C explicitly',
            );
        }
    }


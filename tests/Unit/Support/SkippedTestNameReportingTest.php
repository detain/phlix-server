    private function fixtureFile(string $name, ?string $contents = null): string
    {
        $path = $this->tmpDir . '/' . $name;
        file_put_contents($path, ($contents ?? self::FIXTURE) . "\n");

        return $path;
    }

    /**
     * Writes a throwaway test class whose `setUpBeforeClass()` skips, which is how PHPUnit
     * emits a testSuiteSkipped event. Returns its path.
     */
    private function writeSuiteSkipProbe(): string
    {
        $path = $this->tmpDir . '/S345SuiteSkipProbeTest.php';

        file_put_contents($path, <<<'PROBE'
            <?php

            declare(strict_types=1);

            namespace Phlix\Tests\Scratch;

            use PHPUnit\Framework\TestCase;

            final class S345SuiteSkipProbeTest extends TestCase
            {
                public static function setUpBeforeClass(): void
                {
                    self::markTestSkipped('S345 probe: the whole suite is skipped');
                }

                public function test_never_runs(): void
                {
                    self::assertTrue(true);
                }
            }
            PROBE);

        return $path;
    }

    /**
     * @param list<string> $args
     */
    private function runRealPhpunit(array $args): string
    {
        $root = realpath(self::REPO);
        self::assertIsString($root);
        self::assertFileExists($root . '/vendor/bin/phpunit');

        $command = 'cd ' . escapeshellarg($root) . ' && '
            . escapeshellarg(PHP_BINARY) . ' ' . escapeshellarg($root . '/vendor/bin/phpunit')
            . ' -c ' . escapeshellarg($root . '/phpunit.xml')
            . ' --no-coverage --colors=never';

        foreach ($args as $argument) {
            $command .= ' ' . escapeshellarg($argument);
        }

        $out = $this->tmpDir . '/phpunit-run.txt';
        exec($command . ' > ' . escapeshellarg($out) . ' 2>&1');

        $output = (string) file_get_contents($out);
        @unlink($out);

        self::assertStringContainsString(
            'PHPUnit 10.5',
            $output,
            "the real phpunit binary produced no recognisable output, so nothing below is measuring "
            . "anything:\n" . $output,
        );

        return $output;
    }

    /**
     * Finds a locale installed on this box whose collation orders C_ORDER_PAIR the other
     * way round, DERIVED by running `sort` rather than hard-coded.
     */
    private function localeWhoseCollationDiffersFromC(): ?string
    {
        $file = $this->tmpDir . '/collate.txt';
        file_put_contents($file, self::C_ORDER_PAIR[1] . "\n" . self::C_ORDER_PAIR[0] . "\n");

        $locales = [];
        exec('locale -a 2>/dev/null', $locales);

        foreach ($locales as $locale) {
            if (!str_contains(strtolower($locale), 'utf')) {
                continue;
            }

            $sorted = [];
            exec('LC_ALL=' . escapeshellarg($locale) . ' sort ' . escapeshellarg($file) . ' 2>/dev/null', $sorted);

            if (array_values($sorted) !== self::C_ORDER_PAIR) {
                @unlink($file);

                return $locale;
            }
        }

        @unlink($file);

        return null;
    }

    /**
     * @param array<string, string> $env
     *
     * @return array{exit: int, stdout: string, lines: list<string>, stderr: string}
     */
    private function runScript(string $input, array $env = []): array
    {
        $stdoutFile = $this->tmpDir . '/stdout.txt';
        $stderrFile = $this->tmpDir . '/stderr.txt';

        $prefix = '';
        foreach ($env as $name => $value) {
            $prefix .= $name . '=' . escapeshellarg($value) . ' ';
        }

        $exit = 0;
        exec(
            $prefix . escapeshellarg(self::SCRIPT) . ' ' . escapeshellarg($input)
            . ' > ' . escapeshellarg($stdoutFile) . ' 2> ' . escapeshellarg($stderrFile),
            $ignored,
            $exit,
        );

        $stdout = (string) file_get_contents($stdoutFile);

        return [
            'exit' => $exit,
            'stdout' => $stdout,
            // Deliberately NOT filtered: a blank line is a set member for `comm`, so it must
            // be able to fail an assertion rather than be dropped on the way in.
            'lines' => $stdout === '' ? [] : explode("\n", rtrim($stdout, "\n")),
            'stderr' => (string) file_get_contents($stderrFile),
        ];
    }

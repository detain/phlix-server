    public function test_a_real_testdox_run_is_reported_as_testdox_and_never_blamed_on_phpunit_xml(): void
    {
        $output = $this->runRealPhpunit([self::REAL_TEST_FILE, '--testdox']);

        // The premise, re-derived rather than assumed: testdox counts the skip and never names it.
        self::assertStringContainsString('Skipped: 1', $output, 'the testdox run did not skip anything');
        self::assertStringNotContainsString(
            'skipped test:',
            $output,
            'testdox now prints a skipped-details list — Facade.php changed, so the exit-5 '
            . 'diagnosis needs re-deriving',
        );

        $result = $this->runScript($this->fixtureFile('testdox.log', $output));

        self::assertSame(
            5,
            $result['exit'],
            "a --testdox run must be reported AS a testdox run (exit 5). Exit 4 here would be a\n"
            . "FALSE diagnosis — it blames phpunit.xml, which is correct, and sends the reader to\n"
            . "change a config that cannot affect this. stderr was:\n" . $result['stderr'],
        );
        self::assertSame([], $result['lines'], 'a partial set must not be written');
        self::assertStringContainsString('--testdox', $result['stderr']);
        self::assertStringContainsString('Facade.php:204-221', $result['stderr']);
        self::assertStringNotContainsString(
            'has lost displayDetailsOnSkippedTests',
            $result['stderr'],
            'the testdox case must NOT be diagnosed as a missing attribute — the attribute is '
            . 'present and PHPUnit ignores it on that path',
        );
    }

    public function test_a_real_skipped_test_suite_is_named_rather_than_counted(): void
    {
        $probe = $this->writeSuiteSkipProbe();

        // Suite skip ALONE: PHPUnit prints `No tests executed!` and NO `Tests:` line, so the
        // `Skipped: N` cross-check does not exist for this shape.
        $alone = $this->runRealPhpunit([$probe]);
        self::assertStringContainsString('skipped test suite:', $alone, 'no suite-skip list in the real output');
        self::assertStringContainsString('No tests executed!', $alone);
        self::assertStringNotContainsString('Tests: ', $alone, 'this shape is supposed to publish no totals line');

        $result = $this->runScript($this->fixtureFile('suite-alone.log', $alone));
        self::assertSame(0, $result['exit'], $result['stderr'] . "\n--- phpunit output ---\n" . $alone);
        self::assertSame(['SUITE:Phlix\Tests\Scratch\S345SuiteSkipProbeTest'], $result['lines'], $result['stderr']);

        // Suite skip PLUS a test skip: one `Skipped: 2`, two different headers.
        $mixed = $this->runRealPhpunit([$probe, self::REAL_TEST_FILE]);
        self::assertStringContainsString('Skipped: 2', $mixed, 'a suite skip must count towards Skipped: N');

        $result = $this->runScript($this->fixtureFile('suite-mixed.log', $mixed));
        self::assertSame(
            0,
            $result['exit'],
            "a skipped SUITE is part of `Skipped: N` but is named under its own header, so blaming\n"
            . "the config (exit 4) or the parser (exit 3) for it is a FALSE diagnosis. stderr:\n"
            . $result['stderr'] . "\n--- phpunit output ---\n" . $mixed,
        );
        self::assertSame(
            [
                self::REAL_SKIPPED_NAME,
                'SUITE:Phlix\Tests\Scratch\S345SuiteSkipProbeTest',
            ],
            $result['lines'],
            $result['stderr'],
        );
    }

    public function test_a_real_colorized_run_is_parsed_rather_than_refused(): void
    {
        // `colors="true"` in phpunit.xml means COLOR_AUTO, so a pipe is never colorized in
        // practice — but a human running `--colors=always` and pasting the log must not be told
        // "this is not a PHPUnit run". The summary lines are the ANSI-wrapped ones, which is
